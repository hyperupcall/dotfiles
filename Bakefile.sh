task.build() {
	./lscripts/lint-scripts.py --internal-test-regex

	err=0

	# Every path carrying a git filter attribute must exist, together with the
	# filter programs it depends on. This catches path drift such as a renamed
	# config directory leaving a dead `filter=` rule in .gitattributes.
	local -a _attrs=()
	local _attr= _filter= _smudge=
	while read -r -a _attrs; do
		[ "${#_attrs[@]}" -gt 1 ] || continue
		_filter=
		_smudge=
		for _attr in "${_attrs[@]:1}"; do
			case $_attr in
			filter=*) _filter=${_attr#filter=} ;;
			smudge=*) _smudge=${_attr#smudge=} ;;
			esac
		done
		[ -n "$_filter" ] || continue
		if [ ! -f "${_attrs[0]}" ]; then
			printf 'Git filter target does not exist: %s\n' "${_attrs[0]}"
			err=1
		fi
		if [ ! -f "lscripts/$_filter-clean.sh" ]; then
			printf 'Git filter program does not exist: lscripts/%s-clean.sh\n' "$_filter"
			err=1
		fi
		if [ -n "$_smudge" ] && [ ! -f "lscripts/$_smudge-smudge.sh" ]; then
			printf 'Git filter program does not exist: lscripts/%s-smudge.sh\n' "$_smudge"
			err=1
		fi
	done <.gitattributes

	while read -r file; do
		if grep -q ' _setup ' "$file" && grep -q '^main()' "$file"; then
			printf 'Should not call _setup but define main(): %s\n' "$file"
			err=1
		fi
	done < <(find . \( -name '*.sh' -not -name 'Bakefile.sh' \) -type f)

	# Should have proper ordering of functions. Prefer the repo-local Node
	# install, but fall back to whatever is on PATH (e.g. in CI).
	local node_cmd=node
	if [ -x ./.data/binexec/node ]; then
		node_cmd=./.data/binexec/node
	fi
	if ! "$node_cmd" --input-type=module <<'EOF'; then
	import { readFileSync } from 'fs'
	import { glob } from 'fs/promises'

	const EXPECTED_ORDER = [
		'install.any',
		'install.debian',
		'install.ubuntu',
		'install.fedora',
		'install.opensuse',
		'install.arch',
		'installed',
		'configure',
		'caveats',
	]

	let err = 0

	for await (const file of glob('**/*.sh', { exclude: (p) => p === '.data' || p === 'vendor' })) {
		const lines = readFileSync(file, 'utf8').split('\n')

		if (!lines.some(l => l.includes('_setup '))) continue

		const order = []
		for (const line of lines) {
			for (const name of EXPECTED_ORDER) {
				if (line.startsWith(name + '(')) order.push(name)
			}
		}

		for (let i = 0; i < order.length; i++) {
			for (let j = i + 1; j < order.length; j++) {
				const pi = EXPECTED_ORDER.indexOf(order[i])
				const pj = EXPECTED_ORDER.indexOf(order[j])
				if (pi > pj) {
					console.log(`Bad ordering in ${file}: ${order[j]}() must be before ${order[i]}()`)
					err = 1
				}
			}
		}
	}
	process.exit(err)
EOF
		err=1
	fi

	# Smudged files differ in the working tree from what is committed (e.g. the
	# homedir filter expands ~~~ into $HOME). Skip them here so their smudged
	# private paths aren't reported as forbidden patterns.
	mapfile -t _smudged_files < <(
		git ls-files --cached | while IFS= read -r file; do
			filter=$(git check-attr filter -- "$file" | awk '{print $NF}')
			if [ "$filter" != unspecified ] && [ -n "$(git config --get "filter.$filter.smudge")" ]; then
				printf './%s\n' "$file"
			fi
		done
	)

	# grep '-P' not compatible with with multiple arguments using '-e'.
	for pattern in "${_private_forbidden_patterns[@]}"; do
		if grep -IPr --exclude 'setup-private.*' --exclude .clangd --exclude-dir .git --exclude-dir node_modules --exclude-dir .data --exclude-dir vendor --exclude-dir target --exclude-dir .venv --exclude-dir .cache --exclude-dir .clj-kondo --exclude-dir _site --exclude-dir .jekyll-cache --exclude-dir shell.d --exclude-dir bash.d --exclude-dir zsh.d "${_private_forbidden_patterns_exclude[@]}" --color=always "$pattern" ./ | grep -Ev '(#|//|") lint-ignore' | grep -vF -f <(for f in "${_smudged_files[@]}"; do printf '%s\n' "$f"; done) | grep -v ./config-editor/.config/kate/formatting/settings.json | grep -v pnpm-lock.yaml | grep -v pnpm-workspace.yaml; then
			printf 'Expected to find no matches for: %s\n' "$pattern"
			err=1
		fi
	done

	cd "./config-unused/.config/X11/resources" || exit
	printf '%s\n' "! GENERATED BY 'bake build'" >uxterm.Xresources
	sed 's/XTerm/UXTerm/g' xterm.Xresources >>uxterm.Xresources

	return $err
}

